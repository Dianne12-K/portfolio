// Builds src/data/kenya.js: simplified county outlines as SVG paths.
// Source: geoBoundaries KEN ADM1 (CC BY 4.0). Usage:
//   node scripts/build-kenya.mjs "C:/path/to/ken_ADM1.geojson"
import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) throw new Error('Pass the path to ken_ADM1.geojson')

const TOLERANCE = 0.012 // degrees
const MIN_RING_AREA = 0.004 // square degrees; drops tiny islands
const SCALE = 100 // px per degree (equirectangular is fine this close to the equator)

const geo = JSON.parse(readFileSync(src, 'utf8'))

function perpDist(p, a, b) {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  const len = dx * dx + dy * dy
  if (len === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len))
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy))
}

function simplify(points, tol) {
  const keep = new Uint8Array(points.length)
  keep[0] = keep[points.length - 1] = 1
  const stack = [[0, points.length - 1]]
  while (stack.length) {
    const [s, e] = stack.pop()
    let max = 0
    let idx = -1
    for (let i = s + 1; i < e; i++) {
      const d = perpDist(points[i], points[s], points[e])
      if (d > max) { max = d; idx = i }
    }
    if (max > tol && idx > 0) {
      keep[idx] = 1
      stack.push([s, idx], [idx, e])
    }
  }
  return points.filter((_, i) => keep[i])
}

function ringArea(ring) {
  let a = 0
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1]
  }
  return Math.abs(a / 2)
}

let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity
const counties = geo.features.map((f) => {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  const rings = []
  for (const poly of polys) {
    const outer = poly[0]
    if (ringArea(outer) < MIN_RING_AREA) continue
    for (const [lon, lat] of outer) {
      if (lon < minLon) minLon = lon
      if (lon > maxLon) maxLon = lon
      if (lat < minLat) minLat = lat
      if (lat > maxLat) maxLat = lat
    }
    rings.push(simplify(outer, TOLERANCE))
  }
  return { name: f.properties.shapeName, rings }
})

const pad = 0.15
minLon -= pad; maxLon += pad; minLat -= pad; maxLat += pad
const x = (lon) => ((lon - minLon) * SCALE).toFixed(1)
const y = (lat) => ((maxLat - lat) * SCALE).toFixed(1)

const out = counties
  .filter((c) => c.rings.length)
  .map((c) => ({
    name: c.name,
    d: c.rings.map((r) => 'M' + r.map(([lon, lat]) => `${x(lon)} ${y(lat)}`).join('L') + 'Z').join(''),
  }))

const file = `// Generated by scripts/build-kenya.mjs. Do not edit by hand.
// County boundaries: geoBoundaries KEN ADM1 (CC BY 4.0), simplified.
export const projection = ${JSON.stringify({
  minLon: +minLon.toFixed(4),
  maxLat: +maxLat.toFixed(4),
  scale: SCALE,
  width: +((maxLon - minLon) * SCALE).toFixed(1),
  height: +((maxLat - minLat) * SCALE).toFixed(1),
})}

export const counties = ${JSON.stringify(out)}
`
writeFileSync(new URL('../src/data/kenya.js', import.meta.url), file)
console.log(`${out.length} counties, ${(file.length / 1024).toFixed(0)} KB`)
